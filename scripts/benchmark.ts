/**
 * Runs every algorithm on the five benchmark datasets and writes docs/benchmark-result.md.
 *   pnpm run benchmark            (seed 42)
 *   pnpm run benchmark -- 7       (another seed)
 */
import { mkdirSync, writeFileSync } from 'fs';
import { dirname } from 'path';
import { AlgorithmType } from '../src/common/enums';
import { ScoringService } from '../src/modules/algorithms/scoring/scoring.service';
import { GreedyLocalSearchAlgorithm } from '../src/modules/algorithms/strategies/greedy-local-search.algorithm';
import { GreedyAlgorithm } from '../src/modules/algorithms/strategies/greedy.algorithm';
import { RandomAlgorithm } from '../src/modules/algorithms/strategies/random.algorithm';
import { SimulatedAnnealingAlgorithm } from '../src/modules/algorithms/strategies/simulated-annealing.algorithm';
import { DATASET_DESCRIPTIONS, DATASET_NAMES, buildDataset } from '../src/modules/benchmark/benchmark-datasets';
import { runBenchmark } from '../src/modules/benchmark/benchmark-runner';

const LABEL: Record<string, string> = {
    random: 'Random', greedy: 'Greedy', greedy_local_search: 'Greedy + Local Search', simulated_annealing: 'Simulated Annealing',
};

async function main() {
    const seed = Number(process.argv[2] ?? 42);
    const scoring = new ScoringService();
    const algorithms: Record<string, any> = {
        [AlgorithmType.RANDOM]: new RandomAlgorithm(scoring),
        [AlgorithmType.GREEDY]: new GreedyAlgorithm(scoring),
        [AlgorithmType.GREEDY_LOCAL_SEARCH]: new GreedyLocalSearchAlgorithm(scoring),
        [AlgorithmType.SIMULATED_ANNEALING]: new SimulatedAnnealingAlgorithm(scoring),
    };
    const get = (t: AlgorithmType) => algorithms[t];
    await runBenchmark(get, { seed }); // warm-up so the first timed run is not paying for JIT
    const rows = await runBenchmark(get, { seed });

    const out: string[] = [
        '# Benchmark result',
        '',
        `Generated by \`pnpm run benchmark\` (seed ${seed}) on ${new Date().toISOString().slice(0, 10)}, Node ${process.version}. Every algorithm receives an identical copy of each dataset.`,
        '',
        '- **Hard violations**: placements that break zone, temperature, capacity, vehicle or road-access rules, counted by an independent check of the final plan.',
        '- **Movement cost**: summed road cost (congestion-weighted) or straight-line distance from the entry point; lower is better.',
        '- **Space utilization**: mean of weight and volume load over all unblocked slots; higher means tighter packing (it only differs between algorithms when some cargo is left unplaced).',
        '- **Score**: mean per-product weighted score (0-1 scale of the scoring model); higher is better.',
        '- **Runtime** is wall-clock time on this machine and varies between runs; the other columns do not.',
        '',
    ];
    for (const dataset of DATASET_NAMES) {
        out.push(`## ${dataset}`, '', DATASET_DESCRIPTIONS[dataset], '');
        out.push('| Algorithm | Placed | Hard violations | Movement cost | Space utilization | Runtime (ms) | Score |', '|---|---:|---:|---:|---:|---:|---:|');
        for (const r of rows.filter(x => x.dataset === dataset)) {
            out.push(`| ${LABEL[r.algorithm] ?? r.algorithm} | ${r.assigned}/${r.products} | ${r.hardViolations} | ${r.movementCost} | ${r.spaceUtilization} | ${r.runtimeMs} | ${r.score} |`);
        }
        out.push('');
    }
    const sizes = DATASET_NAMES.map(d => { const c = buildDataset(d, seed); return `${d}: ${c.products.length} products, ${c.slots.length} slots`; });
    out.push('## Dataset sizes', '', ...sizes.map(s => `- ${s}`), '');
    const file = 'docs/benchmark-result.md';
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, out.join('\n'));
    console.log(out.join('\n'));
}
main().catch(e => { console.error(e); process.exit(1); });
